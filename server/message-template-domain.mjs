export const templateCatalog = Object.freeze(definitions.flatMap(([key, name, subject, en, de, required, optional = []]) =>
  ['en', 'de'].map((language, index) => Object.freeze({
    key, name, language, subject: Array.isArray(subject) ? subject[index] : subject,
    message: language === 'en' ? en : de, recipient: '',
    recipientLimit: key.startsWith('facility.') ? 1 : key.startsWith('event.') ? 20 : 0,
    required: Object.freeze(required),
    placeholders: Object.freeze([...new Set([...required, ...optional,
      ...(key.startsWith('facility.') ? ['facility_subject'] : []),
      ...(key.startsWith('event.') ? ['event_title'] : [])])]),
  }))));

export function templateDefinition(key, language) {
  const definition = templateCatalog.find(item => item.key === key && item.language === language);
  if (!definition) throw new Error('Unknown message template or language');
  return definition;
}

function tokens(source) {
  const found = [...source.matchAll(/\{\{([a-z][a-z0-9_]*)\}\}/g)].map(match => match[1]);
  if (/\{\{|\}\}/.test(source.replace(/\{\{([a-z][a-z0-9_]*)\}\}/g, ''))) {
    throw new Error('Use placeholders in the form {{placeholder_name}}');
  }
  return found;
}

export function validateTemplate(definition, content) {
  validateRecipient(definition, content.recipient ?? '');
  if (typeof content.subject !== 'string' || content.subject.length > 220 || /[\r\n]/.test(content.subject)
      || (definition.subject && !content.subject.trim()) || (!definition.subject && content.subject !== '')) {
    throw new Error('Use a single-line subject of 1-220 characters; signature, closing and manual rejection templates have no subject');
  }

  if (typeof content.message !== 'string' || !content.message.trim() || content.message.length > 16000) {
    throw new Error('Message must contain 1-16000 characters');
  }
  const subjectTokens = tokens(content.subject), messageTokens = tokens(content.message);
  for (const token of [...subjectTokens, ...messageTokens]) {
    if (!definition.placeholders.includes(token)) throw new Error(`Unknown placeholder: {{${token}}}`);
  }
  for (const token of subjectTokens) {
    if (!['facility_subject', 'requester_name', 'event_title'].includes(token)) throw new Error(`{{${token}}} is not supported in subjects`);
  }
  for (const token of definition.required) {
    if (messageTokens.filter(value => value === token).length !== 1) {
      throw new Error(`Keep {{${token}}} exactly once in the message; QMT generates this content`);
    }
    if (subjectTokens.includes(token)) throw new Error(`{{${token}}} belongs in the message, not the subject`);
  }
  return content;
}

export function validateRecipient(definition, recipient) {
  if (typeof recipient !== 'string' || recipient.length > 5200 || /[\r\n]/.test(recipient)) {
    throw new Error('Recipients must be a single line of email addresses');
  }
  if (!recipient.trim()) return [];
  const addresses = recipient.split(/[,;]/).map(value => value.trim());
  if (!definition.recipientLimit || addresses.length > definition.recipientLimit) {
    throw new Error(`This template allows ${definition.recipientLimit} email recipient(s)`);
  }
  if (addresses.some(value => !z.string().email().max(254).safeParse(value).success)) {
    throw new Error('Use valid email addresses, separated by commas or semicolons');
  }
  return addresses.filter((value, index) => addresses.findIndex(item => item.toLowerCase() === value.toLowerCase()) === index);
}

export function templateRecipients(key, language, automatic, overrides = []) {
  const definition = templateDefinition(key, language);
  const content = overrides.find(item => item.key === key && item.language === language) || definition;
  const custom = validateRecipient(definition, content.recipient ?? '');
  return custom.length ? custom : validateRecipient(definition, automatic.filter(Boolean).join(', '));
}

function replaceValues(source, values) {
  return source.replace(/\{\{([a-z][a-z0-9_]*)\}\}/g, (_match, token) => {
    if (!Object.hasOwn(values, token) || typeof values[token] !== 'string') throw new Error(`Missing value: {{${token}}}`);
    return values[token];
  });
}

export function renderTemplateSubject(key, language, values, overrides = []) {
  const definition = templateDefinition(key, language);
  const content = overrides.find(item => item.key === key && item.language === language) || definition;
  validateTemplate(definition, content);
  const subject = replaceValues(content.subject, values);
  if (subject.length > 220 || /[\r\n]/.test(subject)) throw new Error('Generated subject exceeds email limits');
  return subject;
}

export function renderTemplate(key, language, values, overrides = []) {
  const definition = templateDefinition(key, language);
  const content = overrides.find(item => item.key === key && item.language === language) || definition;
  validateTemplate(definition, content);
  const subject = renderTemplateSubject(key, language, values, overrides), message = replaceValues(content.message, values);
  if (subject.length > 220 || /[\r\n]/.test(subject) || message.length > 16000) {
    throw new Error('Generated message exceeds the email limits; shorten the template or request details');
  }
  return { subject, message };
}
